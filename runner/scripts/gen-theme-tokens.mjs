// Regenerates the API worker's token whitelist from the vendored catalogue.
//
//   node --experimental-strip-types scripts/gen-theme-tokens.mjs
//
// The worker can't import the authoring app's TypeScript, and shipping the whole
// 74 KB catalogue into a Worker to use nothing but its keys would be silly — so
// the key list is generated instead. Re-run this after re-vendoring
// apps/authoring/src/theme/tokens.ts; `pnpm test` fails if the two drift.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { TOKENS_MAPPING } = await import(join(root, "apps/authoring/src/theme/tokens.ts"));

/** Every token key in TOKENS_MAPPING, in catalogue order. */
export function tokenKeys(mapping = TOKENS_MAPPING) {
  const keys = [];
  for (const entries of Object.values(mapping)) {
    for (const entry of entries) {
      const groups = entry.groups ?? [{ tokens: entry.tokens ?? [] }];
      for (const group of groups) for (const token of group.tokens) keys.push(token.key);
    }
  }
  return keys;
}

const keys = tokenKeys();
const duplicates = keys.filter((k, i) => keys.indexOf(k) !== i);
if (duplicates.length) throw new Error(`duplicate token keys: ${[...new Set(duplicates)].join(", ")}`);

// Wrapped at ~100 cols so the generated file reads like the rest of the worker.
const lines = [];
let line = " ";
for (const key of keys) {
  const piece = ` ${JSON.stringify(key)},`;
  if (line.length + piece.length > 100) { lines.push(line); line = " "; }
  line += piece;
}
if (line.trim()) lines.push(line);

writeFileSync(
  join(root, "workers/api/src/theme-tokens.generated.ts"),
  `// Generated by scripts/gen-theme-tokens.mjs — do not edit by hand.
//
// The ${keys.length} token keys of TOKENS_MAPPING (apps/authoring/src/theme/tokens.ts),
// vendored from theme-builder. This is the set /api/theme lets the model write.

export const TOKEN_KEYS: ReadonlySet<string> = new Set([
${lines.join("\n")}
]);
`,
);
console.log(`wrote workers/api/src/theme-tokens.generated.ts — ${keys.length} keys`);
