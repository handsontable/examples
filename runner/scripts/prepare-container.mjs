// Generate Tier-2 container build contexts from the catalog: one Dockerfile +
// package.json per framework (deps baked), plus workers/api/src/frameworks.generated.ts
// (the Worker's framework -> { dev command, port, DO binding } map).
//
// Usage:
//   node scripts/prepare-container.mjs <framework>   # one
//   node scripts/prepare-container.mjs --all         # every Tier-2 framework

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const RUNNER_DIR = path.resolve(__dirname, "..");

// Base image tag MUST match the installed @cloudflare/sandbox version.
const SANDBOX_IMAGE = "docker.io/cloudflare/sandbox:0.12.3";

// Container dev-server command + port, keyed by container name. Each binds to
// 0.0.0.0 so proxyToSandbox can reach it; ports match the Dockerfile EXPOSE.
const DEV = {
  remix: { cmd: "npm run dev -- --host 0.0.0.0 --port 5173", port: 5173 },
  angular: { cmd: "npx --no-install ng serve --host 0.0.0.0 --port 3000 --disable-host-check", port: 3000 },
  next: { cmd: "npx --no-install next dev -p 3000 -H 0.0.0.0", port: 3000 },
  "next-shadcn": { cmd: "npx --no-install next dev -p 3000 -H 0.0.0.0", port: 3000 },
  astro: { cmd: "npx --no-install astro dev --host 0.0.0.0 --port 4321", port: 4321 },
  nuxt: { cmd: "npx --no-install nuxt dev -H 0.0.0.0 -p 3000", port: 3000 },
};

const catalog = JSON.parse(fs.readFileSync(path.join(RUNNER_DIR, "catalog.json"), "utf8"));

const bindingFor = (container) => "SANDBOX_" + container.toUpperCase().replace(/[^A-Z0-9]+/g, "_");
const classFor = (container) =>
  container.split(/[^a-z0-9]+/i).map((s) => s.charAt(0).toUpperCase() + s.slice(1)).join("") + "Sandbox";

function dockerfile(installCommand, port) {
  const run = `${installCommand} --no-audit --no-fund --loglevel=error`;
  return `# Generated by scripts/prepare-container.mjs — do not edit by hand.
# Tier-2 base image with dependencies baked for a fast warm dev server.
# Per-session source files are written into /app at runtime by the Worker.
FROM ${SANDBOX_IMAGE}

WORKDIR /app

COPY package.json ./
RUN ${run}

EXPOSE ${port}
`;
}

function prepareOne(framework) {
  const entry = catalog.examples.find((e) => e.framework === framework);
  if (!entry) throw new Error(`unknown framework: ${framework}`);
  if (entry.tier !== 2) throw new Error(`${framework} is Tier ${entry.tier}; only Tier-2 use containers`);
  const container = entry.container;
  const dev = DEV[container];
  if (!dev) throw new Error(`no dev command mapping for container: ${container}`);
  const pkg = entry.files["/package.json"];
  if (!pkg) throw new Error(`${framework}: no /package.json in catalog`);

  const outDir = path.join(RUNNER_DIR, "containers", container);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "package.json"), pkg);
  fs.writeFileSync(path.join(outDir, "Dockerfile"), dockerfile(entry.installCommand, dev.port));
  console.log(`[prepare-container] ${framework} -> containers/${container}/ (port ${dev.port})`);
  return { framework, container, port: dev.port, cmd: dev.cmd };
}

function writeGenerated(frameworks) {
  const rows = frameworks.map((f) => {
    const binding = bindingFor(f.container);
    return `  ${JSON.stringify(f.framework)}: { cmd: ${JSON.stringify(f.cmd)}, port: ${f.port}, binding: ${JSON.stringify(binding)}, container: ${JSON.stringify(f.container)} },`;
  });
  const bindings = [...new Set(frameworks.map((f) => bindingFor(f.container)))];
  const out = `// Generated by scripts/prepare-container.mjs — do not edit by hand.
// Tier-2 framework -> dev command, port, and Durable Object binding name.

export interface FrameworkDev {
  cmd: string;
  port: number;
  binding: ${bindings.map((b) => JSON.stringify(b)).join(" | ")};
  container: string;
}

export const FRAMEWORK_DEV: Record<string, FrameworkDev> = {
${rows.join("\n")}
};

export const SANDBOX_BINDINGS = [${bindings.map((b) => JSON.stringify(b)).join(", ")}] as const;
`;
  const outPath = path.join(RUNNER_DIR, "workers", "api", "src", "frameworks.generated.ts");
  fs.writeFileSync(outPath, out);
  console.log(`[prepare-container] wrote ${path.relative(RUNNER_DIR, outPath)}`);

  // Emit the wrangler container + DO-binding + migration blocks for reference.
  const containers = [...new Map(frameworks.map((f) => [f.container, f])).values()];
  console.log("\n[prepare-container] wrangler blocks (containers / durable_objects / migrations):");
  console.log(JSON.stringify({
    containers: containers.map((f) => ({
      class_name: classFor(f.container),
      image: `../../containers/${f.container}/Dockerfile`,
      instance_type: "standard",
      max_instances: 2,
    })),
    durable_objects: {
      bindings: containers.map((f) => ({ class_name: classFor(f.container), name: bindingFor(f.container) })),
    },
    migrations: [{ new_sqlite_classes: containers.map((f) => classFor(f.container)), tag: "v1" }],
  }, null, 2));
}

const arg = process.argv[2];
const tier2 = catalog.examples.filter((e) => e.tier === 2).map((e) => e.framework);
const targets = arg === "--all" || !arg ? tier2 : [arg];
const prepared = targets.map(prepareOne);
writeGenerated(catalog.examples.filter((e) => e.tier === 2).map((e) => {
  const container = e.container;
  const dev = DEV[container];
  return { framework: e.framework, container, port: dev.port, cmd: dev.cmd };
}));
